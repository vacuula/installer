#!/bin/sh

# Exit on error
set -eux
echo "[[vacuula-installer-started]]" > /dev/serusb1

# Trap errors and log failures
trap 'log "[[vacuula-installer-failed]]: Script error occurred"' ERR

log () {
    echo "[vacuula-init] $1" >> /emmc/vacuula-init.log
    echo "[vacuula-init] $1" > /dev/ser1
    echo "[vacuula-init] $1" > /dev/serusb1
}

# run once
set -C  # Enable noclobber - prevents overwriting files
# Try to create lock file atomically - only succeeds if it doesn't exist
if echo $$ > /tmp/vacuula_init_lock 2>/dev/null; then
    log "Acquired lock with PID $$"
    set +C  # Disable noclobber
else
    log "Lock already held, exiting"
    echo "[[vacuula-installer-lock-exit]]" > /dev/serusb1
    set +C  # Disable noclobber
    exit 0
fi

if [ -d /emmc/vacuula ]; then
    # this part needs to be done better in future updates, but good enough for initial release
    # if vacuula is already installed, remove all files and reinitialize
    log "Vacuula already installed, removing existing files"
    echo "[[vacuula-installer-reinstalling]]" > /dev/serusb1
    rm -r /emmc/vacuula # remove vacuula
    rm -f /tmp/vacuula_lock # remove lock file
fi

# (re)initialize vacuula
log "Starting vacuula initialization, creating directory"
echo "[[vacuula-installer-installing]]" > /dev/serusb1
mkdir -p /emmc/vacuula

log "Extracting files to /emmc/vacuula"
tar xzf /tmp/upload -C /emmc/vacuula

log "chmod script"
chmod +x /emmc/vacuula/vacuula.sh

log "checking extract"
log "$(ls -lah /emmc/vacuula)"

log "current configuration:"
log "$(qdbc -d /dev/qdb/systemdb "SELECT * FROM StringSettings")"
log "$(qdbc -d /dev/qdb/systemdb "SELECT * FROM IntegerSettings")"
log "$(qdbc -d /dev/qdb/robotdb "SELECT * FROM CloudServiceLevel")"

log "Setting UTCOFFSET to execute vacuula on boot"
VALUE=$(qdbc -f data -d /dev/qdb/systemdb "SELECT Value FROM StringSettings WHERE Name='UTCOFFSET';")
OFFSET="${VALUE%%;*}"
NEW_OFFSET="$OFFSET;{ /emmc/vacuula/vacuula.sh start_mod &}"
qdbc -d /dev/qdb/systemdb "INSERT OR REPLACE INTO StringSettings( Name, Value ) VALUES ( 'UTCOFFSET', '$NEW_OFFSET' );" || true
NEW_VALUE=$(qdbc -f data -d /dev/qdb/systemdb "SELECT Value FROM StringSettings WHERE Name='UTCOFFSET';")
if [ "$NEW_VALUE" != "$NEW_OFFSET" ]; then
    log "Failed to set UTCOFFSET, got: $NEW_VALUE"
    echo "[[vacuula-installer-failed]]" > /dev/serusb1
    exit 1
else
    log "UTCOFFSET set successfully to: $NEW_VALUE"
fi

# set this so that robot will try to relink and register with beehive on next boot
log "Setting BEEHIVELINKED to 1"
qdbc -d /dev/qdb/systemdb "INSERT OR REPLACE INTO IntegerSettings( Name, Value ) VALUES ( 'BEEHIVELINKED', 1 );" || true
NEW_VALUE=$(qdbc -f data -d /dev/qdb/systemdb "SELECT Value FROM IntegerSettings WHERE Name='BEEHIVELINKED';")
if [ "$NEW_VALUE" != "1" ]; then
    log "Failed to set BEEHIVELINKED, got: $NEW_VALUE"
    echo "[[vacuula-installer-failed]]" > /dev/serusb1
    exit 1
else
    log "BEEHIVELINKED set successfully to: $NEW_VALUE"
fi

# turn access point off
log "Setting APDESIRED to 0"
qdbc -d /dev/qdb/systemdb "INSERT OR REPLACE INTO IntegerSettings( Name, Value ) VALUES ( 'APDESIRED', 0 );" || true
NEW_VALUE=$(qdbc -f data -d /dev/qdb/systemdb "SELECT Value FROM IntegerSettings WHERE Name='APDESIRED';")
if [ "$NEW_VALUE" != "0" ]; then
    log "Failed to set APDESIRED, got: $NEW_VALUE"
    echo "[[vacuula-installer-failed]]" > /dev/serusb1
    exit 1
else
    log "APDESIRED set successfully to: $NEW_VALUE"
fi

# get the ip to use from the file generated by the installer    
IP="$(sed -n '1p' /emmc/vacuula/config)"
GEN3_PORT="$(sed -n '2p' /emmc/vacuula/config)"
HOSTNAME="vacuula.local"

log "Setting BEEHIVESERVER to $HOSTNAME"
qdbc -d /dev/qdb/systemdb "INSERT OR REPLACE INTO StringSettings( Name, Value ) VALUES ( 'BEEHIVESERVER', '$HOSTNAME' );" || true
NEW_VALUE=$(qdbc -f data -d /dev/qdb/systemdb "SELECT Value FROM StringSettings WHERE Name='BEEHIVESERVER';")
if [ "$NEW_VALUE" != "$HOSTNAME" ]; then
    log "Failed to set BEEHIVESERVER, got: $NEW_VALUE"
    echo "[[vacuula-installer-failed]]" > /dev/serusb1
    exit 1
else
    log "BEEHIVESERVER set successfully to: $NEW_VALUE"
fi

log "Setting NUCLEOSERVER to $HOSTNAME"
qdbc -d /dev/qdb/systemdb "INSERT OR REPLACE INTO StringSettings( Name, Value ) VALUES ( 'NUCLEOSERVER', '$HOSTNAME' );" || true
NEW_VALUE=$(qdbc -f data -d /dev/qdb/systemdb "SELECT Value FROM StringSettings WHERE Name='NUCLEOSERVER';")
if [ "$NEW_VALUE" != "$HOSTNAME" ]; then
    log "Failed to set NUCLEOSERVER, got: $NEW_VALUE"
    echo "[[vacuula-installer-failed]]" > /dev/serusb1
    exit 1
else
    log "NUCLEOSERVER set successfully to: $NEW_VALUE"
fi

log "Remove arbitrary limitations based on robot model"
qdbc -d /dev/qdb/robotdb "UPDATE CloudServiceLevel SET findMe='basic-1', generalInfo='basic-1', houseCleaning='basic-4', IECtest='advanced-1', localStats='', logCopy='basic-1', manualCleaning='basic-1', maps='basic-2', preferences='basic-2', schedule='basic-2', softwareUpdate='basic-1', spotCleaning='basic-3', wifi='basic-1' WHERE Label='Current';"

log "check config after update:"
log "$(qdbc -d /dev/qdb/systemdb "SELECT * FROM StringSettings")"
log "$(qdbc -d /dev/qdb/systemdb "SELECT * FROM IntegerSettings")"
log "$(qdbc -d /dev/qdb/robotdb "SELECT * FROM CloudServiceLevel")"

log "make the mod"
/emmc/vacuula/vacuula.sh make_mod

# check if keys exist and delete them to force regeneration
if [ -f /emmc/keys/robot_keys/robot_rsa ]; then
    log "delete recently genereted keys to they get regenerated"
    rm -f /emmc/keys/robot_keys/robot_rsa
    rm -f /emmc/keys/robot_keys/robot_rsa.pub.pem
    log "keys deleted, they should be regenerated on next boot"
else
    log "No existing keys found, skipping deletion"
fi

log "making hosts file"
HOSTS_FILE="/emmc/vacuula/hosts"
echo "# Vacuula Installer generated" >> $HOSTS_FILE
echo "$IP vacuula.local" >> $HOSTS_FILE

log "symlinking hosts file"
ln -fsP $HOSTS_FILE /etc/hosts

log "print hosts file"
cat /etc/hosts > /dev/serusb1

log "print vacuula config file"
cat /emmc/vacuula/config > /dev/serusb1

log "Testing DNS resolution for vacuula.local"
ping -c 1 -w 2 vacuula.local > /dev/serusb1 2>&1 || true

log "openssl connect test"
openssl s_client -connect vacuula.local:$GEN3_PORT -quiet -no_ign_eof </dev/null > /dev/serusb1 2>&1 &
OPID=$!
( sleep 5; kill $OPID 2>/dev/null ) &
KPID=$!
RC=0
wait $OPID 2>/dev/null || RC=$?
kill $KPID 2>/dev/null || true
log "openssl finished, rc=${RC}"

log "Initialization complete"
echo "[[vacuula-installer-finished]]" > /dev/serusb1
log "Rebooting..."
sync
shutdown